import { qualifiedName, quoteIdent } from './format.js';

// SQL for the table structure form: CREATE TABLE for a new table, and for an existing one the ALTER
// statements that turn its columns into the edited ones. Only what changed is written, so attributes
// the form doesn't show are left alone. Types and defaults are SQL typed by the user, used as they are.
//
// A form column is { name, type, nullable, default, primaryKey, autoIncrement, comment, original, dropped }:
// `default` is SQL text ('' for none) and `original` is the column as /api/structure described it
// (null for a column added in the form).

const INDENT = '    ';

/**
 * What each system supports. `alter` lists the fields of an existing column that can be changed; a column
 * added to an existing table can use every field, except that SQLite can't add primary key columns.
 */
export const FEATURES = {
	mysql: { comments: true, autoIncrement: true, alter: ['name', 'type', 'nullable', 'default', 'primaryKey', 'autoIncrement', 'comment'], transactional: false },
	postgres: { comments: true, autoIncrement: true, alter: ['name', 'type', 'nullable', 'default', 'primaryKey', 'comment'], transactional: true },
	sqlite: { comments: false, autoIncrement: false, alter: ['name'], transactional: true },
};

/** Common types offered in the type field (any other type can be typed in). */
export const TYPES = {
	mysql: ['int', 'bigint', 'smallint', 'tinyint(1)', 'decimal(10,2)', 'double', 'varchar(255)', 'char(36)', 'text', 'longtext', 'date', 'datetime', 'timestamp', 'time', 'json', 'blob', "enum('a','b')"],
	postgres: ['integer', 'bigint', 'smallint', 'numeric(10,2)', 'double precision', 'boolean', 'varchar(255)', 'text', 'uuid', 'date', 'timestamp', 'timestamptz', 'time', 'jsonb', 'bytea'],
	sqlite: ['INTEGER', 'REAL', 'TEXT', 'BLOB', 'NUMERIC'],
};

/** Form state for a column described by /api/structure. */
export function formColumn(column) {
	return {
		name: column.name,
		type: column.type,
		nullable: column.nullable,
		default: column.default ?? '',
		primaryKey: column.primaryKey,
		autoIncrement: column.autoIncrement,
		comment: column.comment ?? '',
		original: column,
		dropped: false,
	};
}

export function newColumn() {
	return { name: '', type: '', nullable: true, default: '', primaryKey: false, autoIncrement: false, comment: '', original: null, dropped: false };
}

/** Whether a field of a column can be changed in the form. */
export function canEdit(driver, column, field, { creating = false } = {}) {
	if (creating) return true;
	if (!column.original) return !(driver === 'sqlite' && field === 'primaryKey');
	if (column.original.generated) return field === 'name';
	return FEATURES[driver].alter.includes(field);
}

const isNullable = (c) => c.nullable && !c.primaryKey;
const defaultOf = (c) => c.default.trim() || null;

function differs(c, field) {
	const o = c.original;
	switch (field) {
		case 'name': return c.name.trim() !== o.name;
		case 'type': return c.type.trim() !== o.type;
		case 'nullable': return isNullable(c) !== o.nullable;
		case 'default': return defaultOf(c) !== (o.default ?? null);
		case 'autoIncrement': return c.autoIncrement !== o.autoIncrement;
		case 'comment': return c.comment !== (o.comment ?? '');
	}
}

function literal(driver, text) {
	const escaped = text.replaceAll("'", "''");
	return "'" + (driver === 'mysql' ? escaped.replaceAll('\\', '\\\\') : escaped) + "'";
}

function check(driver, table, columns) {
	if (!table.trim()) throw new Error('Enter a table name.');
	if (!columns.length) throw new Error('A table needs at least one column.');
	const seen = new Set();
	for (const c of columns) {
		const name = c.name.trim();
		if (!name) throw new Error('Every column needs a name.');
		// PostgreSQL's quoted names are case-sensitive; MySQL's and SQLite's column names are not.
		const key = driver === 'postgres' ? name : name.toLowerCase();
		if (seen.has(key)) throw new Error(`Duplicate column name: ${name}`);
		seen.add(key);
		if (!c.type.trim()) throw new Error(`Enter a type for column ${name}.`);
		if (driver === 'postgres' && c.autoIncrement && !c.original?.autoIncrement && defaultOf(c) !== null) {
			throw new Error(`Column ${name} can't have a default and be auto-increment.`);
		}
	}
	return columns;
}

/** One column as written in CREATE TABLE / ADD COLUMN (MySQL: also CHANGE COLUMN). */
function columnDefinition(driver, c) {
	const parts = [quoteIdent(driver, c.name.trim()), c.type.trim()];
	const o = c.original;
	if (driver === 'mysql' && o?.collation && c.type.trim() === o.type) parts.push('COLLATE ' + o.collation);
	if (driver === 'postgres' && c.autoIncrement) parts.push('GENERATED BY DEFAULT AS IDENTITY');
	if (!isNullable(c)) parts.push('NOT NULL');
	else if (driver === 'mysql') parts.push('NULL'); // TIMESTAMP columns are NOT NULL unless told otherwise
	if (defaultOf(c) !== null) parts.push('DEFAULT ' + defaultOf(c));
	if (driver === 'mysql') {
		if (o?.onUpdate) parts.push('ON UPDATE ' + o.onUpdate);
		if (c.autoIncrement) parts.push('AUTO_INCREMENT');
		if (c.comment) parts.push('COMMENT ' + literal(driver, c.comment));
	}
	return parts.join(' ');
}

const keyList = (driver, columns) => columns.map((c) => quoteIdent(driver, c.name.trim())).join(', ');

/** The statements that create a table. `schema` qualifies the name (PostgreSQL schema, attached SQLite database). */
export function createTableSql(driver, { table, schema = null, columns }) {
	check(driver, table, columns);
	const ref = qualifiedName(driver, table.trim(), schema);
	const lines = columns.map((c) => columnDefinition(driver, c));
	const keys = columns.filter((c) => c.primaryKey);
	if (keys.length) lines.push(`PRIMARY KEY (${keyList(driver, keys)})`);
	const statements = [`CREATE TABLE ${ref} (\n${lines.map((line) => INDENT + line).join(',\n')}\n)`];
	if (driver === 'postgres') {
		for (const c of columns.filter((c) => c.comment)) {
			statements.push(`COMMENT ON COLUMN ${ref}.${quoteIdent(driver, c.name.trim())} IS ${literal(driver, c.comment)}`);
		}
	}
	return statements;
}

/**
 * The statements that change table `table` into `name` with `columns` (existing ones, possibly marked
 * `dropped`, and new ones). PostgreSQL needs the name of the primary key constraint to change the key.
 * An empty list means nothing changed.
 */
export function alterTableSql(driver, { table, schema = null, name = table, columns, primaryKeyName = null }) {
	const kept = check(driver, name, columns.filter((c) => !c.dropped));
	const q = (n) => quoteIdent(driver, n);
	const ref = qualifiedName(driver, table, schema);
	const existing = kept.filter((c) => c.original);
	const dropped = columns.filter((c) => c.dropped && c.original);
	const added = kept.filter((c) => !c.original);
	const renamed = existing.filter((c) => differs(c, 'name'));
	const renameTable = name.trim() !== table;

	const oldKeys = columns.filter((c) => c.original?.primaryKey);
	const newKeys = kept.filter((c) => c.primaryKey);
	const keysChanged = oldKeys.length !== newKeys.length || oldKeys.some((c) => c.dropped || !c.primaryKey);

	if (driver === 'mysql') {
		const clauses = [];
		if (keysChanged && oldKeys.length) clauses.push('DROP PRIMARY KEY');
		for (const c of dropped) clauses.push(`DROP COLUMN ${q(c.original.name)}`);
		for (const c of existing) {
			if (['type', 'nullable', 'default', 'autoIncrement', 'comment'].some((field) => differs(c, field))) {
				clauses.push(`CHANGE COLUMN ${q(c.original.name)} ${columnDefinition(driver, c)}`);
			} else if (differs(c, 'name')) {
				clauses.push(`RENAME COLUMN ${q(c.original.name)} TO ${q(c.name.trim())}`);
			}
		}
		for (const c of added) clauses.push(`ADD COLUMN ${columnDefinition(driver, c)}`);
		if (keysChanged && newKeys.length) clauses.push(`ADD PRIMARY KEY (${keyList(driver, newKeys)})`);
		if (renameTable) clauses.push(`RENAME TO ${q(name.trim())}`);
		return clauses.length ? [`ALTER TABLE ${ref}\n${clauses.map((clause) => INDENT + clause).join(',\n')}`] : [];
	}

	const alter = (action) => `ALTER TABLE ${ref} ${action}`;
	const statements = [];

	if (driver === 'sqlite') {
		const unsupported = existing.find((c) => ['type', 'nullable', 'default', 'autoIncrement', 'comment'].some((field) => differs(c, field)));
		if (unsupported) throw new Error(`SQLite can't change column ${unsupported.name.trim()} in place; use the SQL tab.`);
		if (keysChanged) throw new Error("SQLite can't change the primary key of an existing table; use the SQL tab.");
		for (const c of dropped) statements.push(alter(`DROP COLUMN ${q(c.original.name)}`));
		for (const c of renamed) statements.push(alter(`RENAME COLUMN ${q(c.original.name)} TO ${q(c.name.trim())}`));
		for (const c of added) statements.push(alter(`ADD COLUMN ${columnDefinition(driver, c)}`));
		if (renameTable) statements.push(alter(`RENAME TO ${q(name.trim())}`));
		return statements;
	}

	// PostgreSQL: one action per statement, run in a transaction. The old key goes first, before any of
	// its columns are dropped (which would drop it implicitly); renames come before changes by new name.
	if (keysChanged && oldKeys.length) {
		if (!primaryKeyName) throw new Error('The primary key constraint name is unknown.');
		statements.push(alter(`DROP CONSTRAINT ${q(primaryKeyName)}`));
	}
	for (const c of dropped) statements.push(alter(`DROP COLUMN ${q(c.original.name)}`));
	for (const c of renamed) statements.push(alter(`RENAME COLUMN ${q(c.original.name)} TO ${q(c.name.trim())}`));
	for (const c of existing) {
		const col = q(c.name.trim());
		if (differs(c, 'type')) statements.push(alter(`ALTER COLUMN ${col} TYPE ${c.type.trim()} USING ${col}::${c.type.trim()}`));
		if (differs(c, 'default')) statements.push(alter(defaultOf(c) === null ? `ALTER COLUMN ${col} DROP DEFAULT` : `ALTER COLUMN ${col} SET DEFAULT ${defaultOf(c)}`));
		if (differs(c, 'nullable')) statements.push(alter(`ALTER COLUMN ${col} ${isNullable(c) ? 'DROP' : 'SET'} NOT NULL`));
	}
	for (const c of added) statements.push(alter(`ADD COLUMN ${columnDefinition(driver, c)}`));
	if (keysChanged && newKeys.length) statements.push(alter(`ADD PRIMARY KEY (${keyList(driver, newKeys)})`));
	for (const c of kept.filter((c) => (c.original ? differs(c, 'comment') : c.comment))) {
		statements.push(`COMMENT ON COLUMN ${ref}.${q(c.name.trim())} IS ${c.comment ? literal(driver, c.comment) : 'NULL'}`);
	}
	if (renameTable) statements.push(alter(`RENAME TO ${q(name.trim())}`));
	return statements;
}

/** Statements as one script for the SQL endpoint and the preview. */
export function joinStatements(statements) {
	return statements.map((s) => s + ';').join('\n\n');
}
