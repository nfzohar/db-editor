import assert from 'node:assert/strict';
import { describe, test } from 'node:test';
import { defaultSql } from '../server/drivers/mysql.js';
import { alterTableSql, canEdit, createTableSql, formColumn, newColumn } from '../src/ddl.js';

const column = (fields) => ({ ...newColumn(), ...fields });

/** Form state for an existing table, as /api/structure describes it. */
const described = (columns) => columns.map((c) => formColumn({ nullable: true, default: null, primaryKey: false, autoIncrement: false, comment: '', ...c }));

describe('createTableSql', () => {
	const columns = [
		column({ name: 'id', type: 'int', nullable: false, primaryKey: true, autoIncrement: true }),
		column({ name: 'name', type: 'varchar(50)', nullable: false, default: "'x'", comment: "it's" }),
		column({ name: 'note', type: 'text' }),
	];

	test('MySQL writes the key, auto-increment, comments and explicit NULL', () => {
		assert.deepEqual(createTableSql('mysql', { table: 'users', columns }), [
			'CREATE TABLE `users` (\n'
			+ '    `id` int NOT NULL AUTO_INCREMENT,\n'
			+ "    `name` varchar(50) NOT NULL DEFAULT 'x' COMMENT 'it''s',\n"
			+ '    `note` text NULL,\n'
			+ '    PRIMARY KEY (`id`)\n'
			+ ')',
		]);
	});

	test('PostgreSQL uses an identity column and separate comments', () => {
		assert.deepEqual(createTableSql('postgres', { table: 'users', schema: 'app', columns }), [
			'CREATE TABLE "app"."users" (\n'
			+ '    "id" int GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n'
			+ `    "name" varchar(50) NOT NULL DEFAULT 'x',\n`
			+ '    "note" text,\n'
			+ '    PRIMARY KEY ("id")\n'
			+ ')',
			`COMMENT ON COLUMN "app"."users"."name" IS 'it''s'`,
		]);
	});

	test('a primary key column is never nullable', () => {
		const [sql] = createTableSql('sqlite', { table: 't', columns: [column({ name: 'a', type: 'TEXT', nullable: true, primaryKey: true })] });
		assert.match(sql, /"a" TEXT NOT NULL/);
	});

	test('rejects incomplete forms', () => {
		const create = (table, cols, driver = 'sqlite') => () => createTableSql(driver, { table, columns: cols });
		assert.throws(create(' ', columns), /table name/);
		assert.throws(create('t', []), /at least one column/);
		assert.throws(create('t', [column({ name: '', type: 'int' })]), /needs a name/);
		assert.throws(create('t', [column({ name: 'a', type: ' ' })]), /type for column a/);
		assert.throws(create('t', [column({ name: 'a', type: 'int' }), column({ name: 'A', type: 'int' })]), /Duplicate column name: A/);
		assert.doesNotThrow(create('t', [column({ name: 'a', type: 'int' }), column({ name: 'A', type: 'int' })], 'postgres'));
		assert.throws(create('t', [column({ name: 'a', type: 'int', autoIncrement: true, default: '1' })], 'postgres'), /default and be auto-increment/);
	});
});

describe('alterTableSql', () => {
	const table = () => described([
		{ name: 'id', type: 'int', nullable: false, primaryKey: true, autoIncrement: true },
		{ name: 'name', type: 'varchar(50)', nullable: false, default: "'x'", collation: 'utf8mb4_bin', onUpdate: null },
		{ name: 'old', type: 'text' },
	]);

	test('an unchanged form needs no statements', () => {
		for (const driver of ['mysql', 'postgres', 'sqlite']) assert.deepEqual(alterTableSql(driver, { table: 't', columns: table(), primaryKeyName: 't_pkey' }), []);
	});

	test('MySQL changes everything in one statement, renaming without rewriting where it can', () => {
		const columns = table();
		columns[1].name = 'title';
		columns[1].nullable = true;
		columns[2].name = 'older';
		columns.push(column({ name: 'created', type: 'datetime', nullable: false, default: 'CURRENT_TIMESTAMP' }));
		assert.deepEqual(alterTableSql('mysql', { table: 't', name: 't2', columns }), [
			'ALTER TABLE `t`\n'
			+ '    CHANGE COLUMN `name` `title` varchar(50) COLLATE utf8mb4_bin NULL DEFAULT \'x\',\n'
			+ '    RENAME COLUMN `old` TO `older`,\n'
			+ '    ADD COLUMN `created` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,\n'
			+ '    RENAME TO `t2`',
		]);
	});

	test('MySQL keeps ON UPDATE and drops the collation when the type changes', () => {
		const columns = described([{ name: 'at', type: 'timestamp', nullable: false, default: 'CURRENT_TIMESTAMP', onUpdate: 'CURRENT_TIMESTAMP', collation: null },
			{ name: 's', type: 'varchar(5)', collation: 'utf8mb4_bin' }]);
		columns[0].comment = 'changed';
		columns[1].type = 'int';
		assert.deepEqual(alterTableSql('mysql', { table: 't', columns }), [
			'ALTER TABLE `t`\n'
			+ "    CHANGE COLUMN `at` `at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'changed',\n"
			+ '    CHANGE COLUMN `s` `s` int NULL',
		]);
	});

	test('MySQL replaces a changed primary key', () => {
		const columns = table();
		columns[0].dropped = true;
		columns[1].primaryKey = true;
		assert.deepEqual(alterTableSql('mysql', { table: 't', columns }), [
			'ALTER TABLE `t`\n    DROP PRIMARY KEY,\n    DROP COLUMN `id`,\n    ADD PRIMARY KEY (`name`)',
		]);
	});

	test('PostgreSQL writes one action per statement, the old key first and the table rename last', () => {
		const columns = table();
		columns[0].primaryKey = false;
		columns[1].name = 'title';
		columns[1].type = 'text';
		columns[1].default = '';
		columns[1].primaryKey = true;
		columns[1].comment = 'Title';
		columns[2].dropped = true;
		columns.push(column({ name: 'n', type: 'integer', nullable: false, autoIncrement: true }));
		assert.deepEqual(alterTableSql('postgres', { table: 't', schema: 'app', name: 'u', columns, primaryKeyName: 't_pkey' }), [
			'ALTER TABLE "app"."t" DROP CONSTRAINT "t_pkey"',
			'ALTER TABLE "app"."t" DROP COLUMN "old"',
			'ALTER TABLE "app"."t" RENAME COLUMN "name" TO "title"',
			'ALTER TABLE "app"."t" ALTER COLUMN "title" TYPE text USING "title"::text',
			'ALTER TABLE "app"."t" ALTER COLUMN "title" DROP DEFAULT',
			'ALTER TABLE "app"."t" ADD COLUMN "n" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL',
			'ALTER TABLE "app"."t" ADD PRIMARY KEY ("title")',
			`COMMENT ON COLUMN "app"."t"."title" IS 'Title'`,
			'ALTER TABLE "app"."t" RENAME TO "u"',
		]);
	});

	test('PostgreSQL toggles NOT NULL and clears comments', () => {
		const columns = described([{ name: 'a', type: 'text', nullable: false, comment: 'x' }]);
		columns[0].nullable = true;
		columns[0].comment = '';
		assert.deepEqual(alterTableSql('postgres', { table: 't', columns }), [
			'ALTER TABLE "t" ALTER COLUMN "a" DROP NOT NULL',
			'COMMENT ON COLUMN "t"."a" IS NULL',
		]);
	});

	test('SQLite renames, adds and drops columns, and refuses anything else', () => {
		const columns = table();
		columns[1].name = 'title';
		columns[2].dropped = true;
		columns.push(column({ name: 'extra', type: 'TEXT', default: "'-'" }));
		assert.deepEqual(alterTableSql('sqlite', { table: 't', schema: 'aux', name: 'u', columns }), [
			'ALTER TABLE "aux"."t" DROP COLUMN "old"',
			'ALTER TABLE "aux"."t" RENAME COLUMN "name" TO "title"',
			`ALTER TABLE "aux"."t" ADD COLUMN "extra" TEXT DEFAULT '-'`,
			'ALTER TABLE "aux"."t" RENAME TO "u"',
		]);

		const typed = table();
		typed[1].type = 'TEXT';
		assert.throws(() => alterTableSql('sqlite', { table: 't', columns: typed }), /can't change column name/);
		const keyed = table();
		keyed[0].dropped = true;
		assert.throws(() => alterTableSql('sqlite', { table: 't', columns: keyed }), /primary key/);
	});

	test('the form only offers changes the system can make', () => {
		const [id] = table();
		assert.equal(canEdit('sqlite', id, 'type'), false);
		assert.equal(canEdit('sqlite', id, 'name'), true);
		assert.equal(canEdit('sqlite', newColumn(), 'primaryKey'), false);
		assert.equal(canEdit('sqlite', newColumn(), 'primaryKey', { creating: true }), true);
		assert.equal(canEdit('postgres', id, 'autoIncrement'), false);
		assert.equal(canEdit('postgres', newColumn(), 'autoIncrement'), true);
		assert.equal(canEdit('mysql', id, 'autoIncrement'), true);
		assert.equal(canEdit('mysql', formColumn({ ...id.original, generated: true }), 'type'), false);
	});
});

describe('MySQL defaults as SQL', () => {
	test('quotes literals and keeps expressions', () => {
		assert.equal(defaultSql(null, '', false), null);
		assert.equal(defaultSql("it's \\ ok", '', false), "'it''s \\\\ ok'");
		assert.equal(defaultSql('12.5', '', false), '12.5');
		assert.equal(defaultSql('CURRENT_TIMESTAMP', 'DEFAULT_GENERATED', false), 'CURRENT_TIMESTAMP');
		assert.equal(defaultSql('uuid()', 'DEFAULT_GENERATED', false), '(uuid())');
		assert.equal(defaultSql("b'1'", '', false), "b'1'");
	});

	test('passes MariaDB defaults through, which are already SQL', () => {
		assert.equal(defaultSql("'SI'", '', true), "'SI'");
		assert.equal(defaultSql('NULL', '', true), null);
		assert.equal(defaultSql('current_timestamp()', '', true), 'current_timestamp()');
	});
});
